import threading
import time
import uuid
import shutil
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from ocr_parameters import validate_parameters, inference_kwargs

EXTENSIONS = {'.pdf', '.png', '.jpg', '.jpeg', '.webp', '.bmp', '.tif', '.tiff'}
DRIVE = Path(os.environ.get('CT_DRIVE_ROOT', '/content/drive/MyDrive')).resolve()
DATA = Path(os.environ.get('CT_DATA_DIR', str(DRIVE / 'colab-llm/unlimited-ocr')))
MODEL_REVISION = '0480966938291445591f69f08a13b041c073a96a'


def drive_path(spec: str) -> Path:
    if not isinstance(spec, str) or not spec.strip():
        raise ValueError('The Drive path cannot be empty')
    spec = spec.removeprefix('drive://')
    if spec == 'MyDrive':
        spec = '.'
    elif spec.startswith('MyDrive/'):
        spec = spec[len('MyDrive/'):]
    path = Path(spec)
    path = (path if path.is_absolute() else DRIVE / path).resolve()
    if not path.is_relative_to(DRIVE):
        raise ValueError('The path must be inside /content/drive/MyDrive')
    return path


def atomic_json(path: Path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + '.' + uuid.uuid4().hex + '.tmp')
    try:
        temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def discover(specs, recursive=True, output=None):
    if not isinstance(specs, list) or not specs:
        raise ValueError('Specify at least one Drive file or folder')
    found = set()
    for spec in specs:
        root = drive_path(spec)
        if not root.exists():
            raise ValueError(f'Input does not exist: {spec}')
        candidates = (root.rglob('*') if recursive else root.iterdir()) if root.is_dir() else [root]
        for candidate in candidates:
            path = candidate.resolve()
            if not path.is_relative_to(DRIVE):
                continue
            if output and path.is_relative_to(output):
                continue
            if path.is_file() and path.suffix.lower() in EXTENSIONS:
                found.add(path)
    if not found:
        raise ValueError('No PDF or supported image found')
    return sorted(found)


def options(body):
    dpi = int(body.get('dpi', 200))
    pages = int(body.get('pages_per_chunk', 10))
    tokens = int(body.get('tokens_per_page', 8000))
    if not 72 <= dpi <= 400 or not 1 <= pages <= 100 or not 32 <= tokens <= 20000:
        raise ValueError('dpi: 72–400; pages_per_chunk: 1–100; tokens_per_page: 32–20000')
    return dict(dpi=dpi, pages_per_chunk=pages, tokens_per_page=tokens,
                inference_params=validate_parameters(body.get('inference_params', {})))


def file_signature(source, opts):
    stat = source.stat()
    return hashlib.sha256(json.dumps([str(source), stat.st_size, stat.st_mtime_ns,
                                     opts, MODEL_REVISION]).encode()).hexdigest()


def sha256_file(path):
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


class Checkpoints:
    """Commit a page group only after raw text, Markdown and all assets are durable."""
    def __init__(self, destination, signature):
        self.destination = Path(destination)
        self.root = self.destination / '.checkpoints'
        self.signature = signature
        try:
            current = json.loads((self.root / 'state.json').read_text())
        except (OSError, ValueError):
            current = {}
        if current.get('signature') != signature:
            shutil.rmtree(self.root, ignore_errors=True)
            # These names are exclusively generated by this service.
            for path in self.destination.iterdir():
                if re.fullmatch(r'(chunk|native)-[0-9]+', path.name):
                    if path.is_symlink():
                        path.unlink()
                    elif path.is_dir():
                        shutil.rmtree(path)
            atomic_json(self.root / 'state.json', dict(signature=signature, version=1))

    def load(self, start, end):
        try:
            record = json.loads((self.root / f'{start:06d}.json').read_text())
            if (record['signature'] != self.signature or record['end'] != end
                    or not isinstance(record['raw'], str) or not isinstance(record['markdown'], str)
                    or type(record['tokens']) is not int or record['tokens'] < 0):
                return None
            for name, digest in record['artifacts'].items():
                path = (self.destination / name).resolve()
                if not path.is_relative_to(self.destination.resolve()) or sha256_file(path) != digest:
                    return None
            return record
        except (OSError, ValueError, KeyError, TypeError, AttributeError):
            return None

    def save(self, start, end, raw, markdown, tokens, artifacts):
        record = dict(signature=self.signature, end=end, raw=raw, markdown=markdown, tokens=tokens,
                      artifacts={str(p.relative_to(self.destination)): sha256_file(p) for p in artifacts})
        atomic_json(self.root / f'{start:06d}.json', record)
        return record


class Engine:
    def __init__(self):
        import torch
        from transformers import AutoModel, AutoTokenizer
        self.torch = torch
        model_dir = os.environ['CT_OCR_MODEL_DIR']
        self.tokenizer = AutoTokenizer.from_pretrained(model_dir, trust_remote_code=True)
        self.model = AutoModel.from_pretrained(
            model_dir, trust_remote_code=True, use_safetensors=True,
            torch_dtype=torch.bfloat16).eval().cuda()
        # Compile and exercise the actual GPU path before health can report ready.
        from PIL import Image, ImageDraw
        image = Image.new('RGB', (512, 512), 'white')
        ImageDraw.Draw(image).text((32, 32), 'OCR ready', fill='black')
        with torch.inference_mode():
            self.model.infer(self.tokenizer, image_file=image, eval_mode=True,
                             max_new_tokens=32, crop_mode=False)

    def infer_pages(self, pages, native_output, opts):
        # infer_multi forces return_dict=True and rewrites prompts; infer preserves all options.
        params = inference_kwargs(opts.get('inference_params', {}), len(pages), opts['tokens_per_page'])
        with self.torch.inference_mode():
            result = self.model.infer(self.tokenizer, image_file=[str(p) for p in pages],
                                      output_path=str(native_output), **params)
        if isinstance(result, dict):
            return result['text'], len(result['token_ids'])
        return result, len(self.tokenizer.encode(result, add_special_tokens=False))

    def convert(self, source: Path, destination: Path, opts, progress):
        import fitz
        from PIL import Image
        from process_unlimitedOCR2 import convert
        destination.mkdir(parents=True, exist_ok=True)
        raw_chunks, markdown_chunks = [], []
        total_tokens = 0
        resumed_chunks = 0
        # Overwrite uses a per-job generation: restart resumes that overwrite, a new job starts fresh.
        checkpoint_signature = hashlib.sha256(json.dumps([
            file_signature(source, {k: v for k, v in opts.items() if not k.startswith('_')}),
            opts.get('_checkpoint_generation', 'shared'), 1]).encode()).hexdigest()
        checkpoints = Checkpoints(destination, checkpoint_signature)
        with tempfile.TemporaryDirectory(prefix='ocr-', dir='/content/unlimited-ocr') as tmp:
            # Render only the current page window, keeping RAM and local disk bounded.
            pdf = fitz.open(source) if source.suffix.lower() == '.pdf' else None
            raster = Image.open(source) if pdf is None else None
            try:
                page_count = len(pdf) if pdf is not None else getattr(raster, 'n_frames', 1)
                for start in range(0, page_count, opts['pages_per_chunk']):
                    end = min(start + opts['pages_per_chunk'], page_count)
                    saved = checkpoints.load(start, end)
                    if saved is not None:
                        raw_chunks.append(saved['raw'])
                        markdown_chunks.append(saved['markdown'])
                        total_tokens += saved['tokens']
                        resumed_chunks += 1
                        progress(end, page_count)
                        continue
                    # A group without a valid commit may contain interrupted/stale assets.
                    for prefix in ('chunk', 'native'):
                        shutil.rmtree(destination / f'{prefix}-{start + 1:04d}', ignore_errors=True)
                    pages = []
                    for index in range(start, min(start + opts['pages_per_chunk'], page_count)):
                        path = Path(tmp) / f'page{index + 1}.png'
                        if pdf is not None:
                            pdf[index].get_pixmap(dpi=opts['dpi'], alpha=False).save(path)
                        else:
                            raster.seek(index)
                            raster.convert('RGB').save(path)
                        pages.append(path)
                    raw, count = self.infer_pages(pages, destination / f'native-{start + 1:04d}', opts)
                    total_tokens += count
                    # Each chunk has its own asset directory; upstream Markdown page indices restart at 1.
                    assets = destination / f'chunk-{start + 1:04d}'
                    assets.mkdir(exist_ok=True)
                    markdown = convert(raw)
                    for name, page, coords in re.findall(
                            r'(page(\d+)_((?:\d+_){3}\d+)\.jpg)', markdown):
                        idx = int(page) - 1
                        if 0 <= idx < len(pages):
                            with Image.open(pages[idx]) as image:
                                x1, y1, x2, y2 = map(int, coords.split('_'))
                                if x2 > x1 and y2 > y1:
                                    image.crop((x1 * image.width / 1000, y1 * image.height / 1000,
                                                x2 * image.width / 1000, y2 * image.height / 1000)).convert('RGB').save(assets / name)
                    markdown = re.sub(r'!\[\]\((page\d+_[\d_]+\.jpg)\)',
                                      lambda m: f'![]({assets.name}/{m[1]})', markdown)
                    artifacts = [p for prefix in ('chunk', 'native')
                                 for p in (destination / f'{prefix}-{start + 1:04d}').rglob('*') if p.is_file()]
                    checkpoints.save(start, end, raw, markdown, count, artifacts)
                    raw_chunks.append(raw)
                    markdown_chunks.append(markdown)
                    for path in pages:
                        path.unlink()
                    progress(min(start + len(pages), page_count), page_count)
                if not page_count:
                    raise ValueError('The document has no pages')
            finally:
                if pdf is not None:
                    pdf.close()
                if raster is not None:
                    raster.close()
        (destination / 'result.raw.txt').write_text('\n'.join(raw_chunks), encoding='utf-8')
        (destination / 'result.md').write_text('\n\n'.join(markdown_chunks), encoding='utf-8')
        return dict(pages=page_count, tokens=total_tokens, chunks=len(raw_chunks), resumed_chunks=resumed_chunks)


class Jobs:
    def __init__(self, engine, data=DATA, start_worker=True):
        self.engine = engine
        self.root = Path(data) / 'jobs'
        self.root.mkdir(parents=True, exist_ok=True)
        self.lock = threading.Lock()
        self.queue = queue.Queue()
        recovered = []
        for path in self.root.glob('*.json'):
            try:
                record = json.loads(path.read_text())
                if record['status'] in ('queued', 'running'):
                    self.prepare_resume(record, automatic=True)
                    self.save(record)
                    recovered.append(record)
            except (OSError, ValueError, KeyError, TypeError) as error:
                print(f'[recovery] skipped invalid job record {path.name}: {error}', flush=True)
        for record in sorted(recovered, key=lambda item: item.get('created', 0)):
            self.queue.put(record)
        if start_worker:
            threading.Thread(target=self.worker, daemon=True).start()

    @staticmethod
    def prepare_resume(record, automatic=False):
        # Validate persisted settings before putting them back on the GPU queue.
        record['options'] = options(record['options'])
        if not record.get('files') or not re.fullmatch(r'[0-9a-f]{32}', record['id']):
            raise ValueError('Invalid job record')
        record.update(status='queued', resume_count=record.get('resume_count', 0) + 1,
                      resumed_at=time.time(), automatic_resume=automatic)
        record.pop('error', None)
        record.pop('finished', None)
        for item in record['files']:
            if item['status'] not in ('completed', 'skipped'):
                item['status'] = 'queued'
                item.pop('error', None)

    def resume(self, job_id):
        # One lock covers validation and persisted transition, so duplicate resume cannot enqueue twice.
        if not re.fullmatch(r'[0-9a-f]{32}', job_id):
            raise ValueError('Invalid job ID')
        with self.lock:
            path = self.root / (job_id + '.json')
            record = json.loads(path.read_text())
            if record['status'] in ('queued', 'running', 'completed'):
                raise ValueError('The job is already queued, running or completed')
            self.prepare_resume(record)
            atomic_json(path, record)
            self.queue.put(record)
        return record

    def get(self, job_id):
        if not re.fullmatch(r'[0-9a-f]{32}', job_id):
            raise ValueError('Invalid job ID')
        with self.lock:
            return json.loads((self.root / (job_id + '.json')).read_text())

    def save(self, record):
        with self.lock:
            atomic_json(self.root / (record['id'] + '.json'), record)

    def submit(self, body):
        opts = options(body)
        output = drive_path(body.get('output_dir') or str(DATA / 'outputs'))
        paths = discover(body.get('inputs'), body.get('recursive', True), output)
        if any(output == path or output.is_relative_to(path) for path in paths):
            raise ValueError('The output directory cannot be inside an input file')
        job = dict(id=uuid.uuid4().hex, status='queued', created=time.time(), options=opts,
                   output_dir=str(output), overwrite=bool(body.get('overwrite', False)),
                   files=[dict(source=str(p), status='queued',
                               relative_output=body.get('relative_outputs', {}).get(str(p), str(p.relative_to(DRIVE)))) for p in paths])
        for item in job['files']:
            relative = Path(item['relative_output'])
            if relative.is_absolute() or '..' in relative.parts or not relative.parts:
                raise ValueError('Invalid relative output path')
        if len({item['relative_output'] for item in job['files']}) != len(paths):
            raise ValueError('Relative output paths of several source files conflict')
        self.save(job)
        self.queue.put(job)
        return job

    def worker(self):
        while True:
            job = self.queue.get()
            try:
                self.run(job)
            except Exception as error:
                job.update(status='failed', error=str(error))
                self.save(job)
            finally:
                self.queue.task_done()

    def run(self, job):
        job['status'] = 'running'
        self.save(job)
        for item in job['files']:
            source = Path(item['source'])
            destination = drive_path(str(Path(job['output_dir']) / item.get('relative_output', str(source.relative_to(DRIVE)))))
            marker = destination / 'complete.json'
            try:
                signature = file_signature(source, job['options'])
                if (not job['overwrite'] or item.get('completed_signature') == signature) and marker.is_file():
                    previous = json.loads(marker.read_text())
                    if previous.get('signature') == signature and (destination / 'result.md').is_file():
                        item.update(status='skipped', output=str(destination))
                        self.save(job)
                        continue
                # An old completion marker must never validate a partially overwritten result.
                marker.unlink(missing_ok=True)
                item['status'] = 'running'
                item.pop('error', None)
                self.save(job)
                def progress(done, total):
                    item.update(pages_done=done, pages_total=total)
                    self.save(job)
                conversion_opts = {**job['options'],
                                   '_checkpoint_generation': job['id'] if job['overwrite'] else 'shared'}
                result = self.engine.convert(source, destination, conversion_opts, progress)
                if file_signature(source, job['options']) != signature:
                    raise ValueError('A source file changed during conversion; resume the job to reprocess it')
                atomic_json(marker, dict(signature=signature, source=str(source), options=job['options'], **result))
                item.update(status='completed', output=str(destination), completed_signature=signature, **result)
            except Exception as error:
                item.update(status='failed', error=str(error))
            self.save(job)
        job.update(status='failed' if any(f['status'] == 'failed' for f in job['files']) else 'completed',
                   finished=time.time())
        self.save(job)


def upload_chunk(body):
    """Stage local input in a content-addressed Drive inbox, in bounded chunks."""
    digest = body.get('sha256', '')
    name = body.get('name', '')
    if not re.fullmatch(r'[0-9a-f]{64}', digest) or Path(name).name != name or Path(name).suffix.lower() not in EXTENSIONS:
        raise ValueError('Invalid upload name or SHA256')
    offset = int(body.get('offset', 0))
    chunk = base64.b64decode(body.get('data', ''), validate=True)
    if offset < 0 or len(chunk) > 512 * 1024:
        raise ValueError('Invalid chunk size/offset')
    folder = drive_path(str(DATA / 'uploads' / digest))
    folder.mkdir(parents=True, exist_ok=True)
    destination = folder / name
    temporary = folder / (name + '.part')
    if destination.exists():
        return dict(path=str(destination), complete=True)
    if offset == 0:
        temporary.write_bytes(chunk)
    else:
        if not temporary.exists() or temporary.stat().st_size != offset:
            raise ValueError('Upload offset mismatch; retry the upload')
        with temporary.open('ab') as stream:
            stream.write(chunk)
    if body.get('final'):
        hasher = hashlib.sha256()
        with temporary.open('rb') as stream:
            for block in iter(lambda: stream.read(1024 * 1024), b''):
                hasher.update(block)
        if hasher.hexdigest() != digest:
            temporary.unlink()
            raise ValueError('Upload SHA256 verification failed')
        os.replace(temporary, destination)
    return dict(path=str(destination), complete=destination.exists())


def result_files(jobs, job_id, index, name=None, offset=0):
    record = jobs.get(job_id)
    item = record['files'][index]
    if item['status'] not in ('completed', 'skipped'):
        raise ValueError('The file has not finished converting')
    root = drive_path(item['output'])
    if name is None:
        return dict(files=[str(p.relative_to(root)) for p in sorted(root.rglob('*'))
                           if p.is_file() and '.checkpoints' not in p.relative_to(root).parts
                           and p.resolve().is_relative_to(root)])
    target = (root / name).resolve()
    if not target.is_relative_to(root) or not target.is_file() or offset < 0:
        raise ValueError('Invalid result file path/offset')
    with target.open('rb') as stream:
        stream.seek(offset)
        chunk = stream.read(512 * 1024)
    return dict(data=base64.b64encode(chunk).decode(), next_offset=offset + len(chunk),
                complete=offset + len(chunk) >= target.stat().st_size)


def serve():
    engine = Engine()
    jobs = Jobs(engine)

    class Handler(BaseHTTPRequestHandler):
        def send_json(self, code, value):
            raw = json.dumps(value, ensure_ascii=False).encode()
            self.send_response(code)
            self.send_header('Content-Type', 'application/json; charset=utf-8')
            self.send_header('Content-Length', str(len(raw)))
            self.end_headers()
            self.wfile.write(raw)

        def do_GET(self):
            try:
                if self.path in ('/', '/health'):
                    return self.send_json(200, dict(status='ready', model='baidu/Unlimited-OCR-2'))
                if self.path.startswith('/api/jobs/'):
                    return self.send_json(200, jobs.get(self.path.removeprefix('/api/jobs/')))
                self.send_json(404, dict(error='not found'))
            except FileNotFoundError:
                self.send_json(404, dict(error='job not found'))
            except ValueError as error:
                self.send_json(400, dict(error=str(error)))

        def do_POST(self):
            try:
                size = int(self.headers.get('Content-Length', '0'))
                if not 0 < size <= 1024 * 1024:
                    raise ValueError('Invalid request length')
                body = json.loads(self.rfile.read(size))
                if not isinstance(body, dict):
                    raise ValueError('JSON body must be an object')
                if self.path == '/api/upload':
                    return self.send_json(200, upload_chunk(body))
                if self.path == '/api/results':
                    return self.send_json(200, result_files(jobs, body['job_id'], int(body['index']),
                        body.get('name'), int(body.get('offset', 0))))
                if re.fullmatch(r'/api/jobs/[0-9a-f]{32}/resume', self.path):
                    return self.send_json(202, jobs.resume(self.path.split('/')[3]))
                if self.path == '/api/jobs':
                    return self.send_json(202, jobs.submit(body))
                if self.path == '/api/drive-list':
                    return self.send_json(200, dict(files=[str(p.relative_to(DRIVE)) for p in
                        discover(body.get('inputs'), body.get('recursive', True))]))
                self.send_json(404, dict(error='not found'))
            except (ValueError, TypeError, OSError, KeyError, IndexError) as error:
                self.send_json(400, dict(error=str(error)))

    ThreadingHTTPServer(('127.0.0.1', int(os.environ.get('CT_SERVICE_PORT', '8000'))), Handler).serve_forever()


if __name__ == '__main__':
    serve()
